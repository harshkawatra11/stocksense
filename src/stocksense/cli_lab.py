def serve(
    ctx: typer.Context,
    port: Annotated[int, typer.Option(help="Port on 127.0.0.1 (Market Lab uses 8810).")] = 8765,
    no_feeds: Annotated[bool, typer.Option(help="Do not start the live feed threads.")] = False,
    no_catchup: Annotated[
        bool, typer.Option(help="Do not run the startup catch-up (ingest, panel, scan).")
    ] = False,
) -> None:
    """Start the local dashboard server on 127.0.0.1 (manual start only; Ctrl+C stops it)."""
    import uvicorn

    from stocksense.api.app import create_app
    from stocksense.cli import _settings

    app = create_app(_settings(ctx), start_feeds=not no_feeds)
    app.state.catchup_enabled = not no_catchup
    uvicorn.run(app, host="127.0.0.1", port=port, workers=1, log_level="info")


def _diff(a: Any, b: Any, path: str, bad: list[str]) -> None:
    """Collect differences between two JSON values (floats compared to 1e-9, NaN equal NaN)."""
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            bad.append(f"{path}: keys differ {sorted(set(a) ^ set(b))}")
            return
        for k in a:
            _diff(a[k], b[k], f"{path}.{k}", bad)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            bad.append(f"{path}: length {len(a)} vs {len(b)}")
            return
        for i, (x, y) in enumerate(zip(a, b, strict=True)):
            _diff(x, y, f"{path}[{i}]", bad)
    elif isinstance(a, float) or isinstance(b, float):
        nums = isinstance(a, (int, float)) and isinstance(b, (int, float))
        both_nan = nums and math.isnan(a) and math.isnan(b)
        if not both_nan and not (nums and math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-9)):
            bad.append(f"{path}: {a} vs {b}")
    elif a != b:
        bad.append(f"{path}: {a!r} vs {b!r}")


@lab_app.command("golden-check")
def golden_check(
    clone: Annotated[Path, typer.Option(help="Local market-lab clone.")] = DEFAULT_CLONE,
) -> None:
    """Re-run Market Lab's own functions in its own venv and diff against the committed golden files."""
    py = clone / ".venv" / "Scripts" / "python.exe"
    if not py.exists():
        typer.echo(f"clone interpreter not found: {py} (nothing is installed into it)")
        raise typer.Exit(2)
    with tempfile.TemporaryDirectory() as tmp:
        for f in FIXTURES.glob("inputs_*.json"):
            shutil.copy(f, tmp)
        script = REPO / "scripts" / "golden" / "run_marketlab.py"
        run = subprocess.run(
            [str(py), "-I", str(script), str(clone), tmp], capture_output=True, text=True, check=False
        )
        if run.returncode != 0:
            typer.echo(run.stderr[-800:])
            raise typer.Exit(1)
        bad: list[str] = []
        for new in sorted(Path(tmp).glob("golden_*.json")):
            old = FIXTURES / new.name
            _diff(json.loads(new.read_text("utf-8")), json.loads(old.read_text("utf-8")), new.stem, bad)
    for line in bad[:30]:
        typer.echo(line)
    typer.echo("golden files match" if not bad else f"{len(bad)} differences")
    raise typer.Exit(1 if bad else 0)


def registry_toml_text() -> str:
    """TOML text of every registered strategy, one `[strategy.<key>]` section each (PLAN-M M5.0 format)."""
    from stocksense.strategies.base import load_library

    q = json.dumps
    lines = [
        "# Generated by `stocksense lab registry-toml`; review by hand, then pre-register (PLAN-M rule 13).",
        "",
    ]
    for key, s in sorted(load_library().items()):
        lines += [
            f"[strategy.{key}]",
            f"name = {q(s.name)}",
            f"source = {q(s.source)}",
            f"tier = {q(s.tier)}",
            f"family = {q(s.family)}",
            f"timeframe = {q(s.timeframe)}",
            f"kind = {q(s.kind)}",
            f"direction = {q(s.direction)}",
            f"exits = {q(list(s.exits))}",
            f"default_exit = {q(s.default_exit)}",
            "params = {}",
            f"strength = {q(s.strength)}",
            f"hypothesis = {q(s.description.splitlines()[0] if s.description else '')}",
            f"reference = {q(s.reference)}",
            "",
        ]
    return chr(10).join(lines)


@lab_app.command("registry-toml")
def registry_toml() -> None:
    """Print the strategy registry as TOML (redirect into config/strategy_library.toml, then review)."""
    typer.echo(registry_toml_text())


def _last_session(settings: Any) -> date:
    from stocksense.core.calendar import TradingCalendar
    from stocksense.core.clock import SystemClock
    from stocksense.strategies.data import completed_end

    clock = SystemClock()
    return completed_end(clock, TradingCalendar.from_store(settings, clock), settings)


@lab_app.command("scan")
def scan(
    ctx: typer.Context,
    asof: Annotated[str | None, typer.Option(help="YYYY-MM-DD; default the last completed session.")] = None,
    workers: Annotated[int, typer.Option(help="Worker processes (1 = in this process).")] = 6,
) -> None:
    """Run the exploratory radar scan on the u500 + F&O universe (exploratory, not evidence)."""
    from stocksense.cli import _settings
    from stocksense.strategies.scan import run_scan

    st = _settings(ctx)
    day = date.fromisoformat(asof) if asof else _last_session(st)
    out = run_scan(st, day, workers=workers)
    typer.echo(f"scan {day}: {out}")


@lab_app.command("explore")
def explore(
    ctx: typer.Context,
    sym: Annotated[str, typer.Option(help="Symbol, e.g. RELIANCE.")],
    strat: Annotated[str, typer.Option(help="Strategy key or Market Lab display name.")],
    exit_: Annotated[str | None, typer.Option("--exit", help="Exit key (default: the strategy's).")] = None,
    tf: Annotated[str, typer.Option(help="1d or 5m.")] = "1d",
) -> None:
    """Print one stock's exploratory trades for a strategy as Market Lab's JSON (not evidence)."""
    from stocksense.cli import _settings
    from stocksense.core.clock import SystemClock
    from stocksense.strategies.explore import trades_for

    try:
        out = trades_for(sym.upper(), strat, exit_, _settings(ctx), SystemClock(), tf)
    except (KeyError, ValueError) as e:
        typer.echo(f"error: {e}")
        raise typer.Exit(2) from e
    typer.echo(json.dumps(out, indent=1))


def register(app: typer.Typer) -> None:
    """Hook for cli.py: add `serve` and the `lab` group."""
    app.command("serve")(serve)
    app.add_typer(lab_app, name="lab")
