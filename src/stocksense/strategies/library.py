"""The pre-registered strategy library: `config/strategy_library.toml` and how each strategy is evaluated
(PLAN-M M5.0).

The file is generated once from the registry (`stocksense lab registry-toml`), reviewed by hand and then
frozen by a SHA-pinned test (PLAN-M Part 0 rule 13). This module holds the protocol text, the function that
writes a strategy's section, and the read side used by the gated runner (`validation/strategy_eval.py`):
the section of one key, its evaluation kind, target and benchmark.
"""

from __future__ import annotations

import json
import re
import tomllib
from datetime import date
from functools import lru_cache
from pathlib import Path
from typing import Any

from stocksense.strategies.base import StrategySpec, load_library

LIBRARY_PATH = Path(__file__).resolve().parents[3] / "config" / "strategy_library.toml"
TRENDS = ("D", "I", "DI")  # intraday trend filters: one trial each
INTRA_EXITS = ("rr1", "rr15", "rr2", "rr3", "be2", "trail", "scale", "eod")

# evaluation kinds (how the gated runner turns a strategy into a daily series)
KIND_SWING = "swing"  # per-stock daily signal -> k-slot book
KIND_INTRA = "intra"  # per-stock 5-minute signal, one trial per trend filter
KIND_XS = "xs"  # cross-sectional score -> preds -> evaluate_model
KIND_INDEX = "book_index"  # k151_idx rule -> run_book
KIND_CAPITAL = "book_capital"  # timing(settings, start, end, capital_inr) returns the book (Appendix A, ANN)
KIND_POSITION = "timing_position"  # timing returns (date, position) on NIFTY
KIND_OPTIONS = "options"  # timing returns (date, ret) (and `.with_cost`): return on underlying notional
KIND_INFO = "informational"  # no trial

PROTOCOL = """\
# Pre-registered on 2026-11-25 before any gated result (PLAN-M Part 0 rule 13). Never edit; add
# strategy_library_<YYYYMMDD>.toml instead. Generated by `stocksense lab registry-toml`, then reviewed by hand.
[protocol]
research_end = 2025-09-30
daily_folds = "calendar years 2014..2025 (validation.splits.walk_forward_folds), embargo 5 sessions"
intraday_folds = "calendar months 2024-10..2025-09, training/inner window = all earlier months from 2024-09-13, embargo 1 session"
universe_daily = "u500 point-in-time (panel_universe.u500 on the signal date)"
universe_intraday = "u200 point-in-time with 5m bars present"
capital_grid = [100000, 200000, 500000, 1000000]
reference_capital = 500000
slots = 10
priority = "rs63"           # same-day signals taken by descending 63-day relative strength vs NIFTY 50 (Market Lab)
costs = "stocksense.costs: delivery for 1d, intraday for 5m/60m; slippage table; net_2x = slippage x2 (options: statutory charges x2)"
exit_selection = "walk_forward_inner: for each test fold, exit with best net Sharpe on all earlier data (minus embargo); min 30 inner trades else default_exit"
intraday_trends = ["D", "I", "DI"]   # one trial per trend filter
gate_version = 2
ic_label_daily = "y_c2o_10"
ic_label_intraday = "y_oc"
ic_books = "series-only books (options, Appendix A, ANN) have no ranked signal: their IC lines are recorded as 0 and fail; index rules use the 21-day block Spearman of exposure vs next-day NIFTY return"
note = "Exploratory per-stock results in the UI are not evidence; only these trials are."

"""  # noqa: E501


def paper_ref(spec: StrategySpec) -> tuple[str, str]:
    """(section, equation) of a *151 Trading Strategies* row from its reference and text ("" if none)."""
    text = f"{spec.reference} {spec.description}"
    sec = re.search(r"\b(?:sec|s)\.?\s*([A-Z]|\d+(?:\.\d+)*)\b", spec.reference)
    eq = re.search(r"eqs?\.\s*([\d]+(?:\s*[-,]\s*\d+)*)", text)
    return (sec.group(1) if sec else ""), (eq.group(1).replace(" ", "") if eq else "")


def eval_kind(spec: StrategySpec) -> str:
    """How the gated runner evaluates a strategy (one of the KIND_* constants)."""
    from stocksense.strategies.k151_idx import INDEX_RULES

    if spec.kind == "options":
        return KIND_OPTIONS
    if spec.key in INDEX_RULES:
        return KIND_INDEX
    if spec.score is not None:
        return KIND_XS
    if spec.timing is not None:
        return KIND_CAPITAL if spec.kind == "event" else KIND_POSITION
    if spec.signal is not None:
        return KIND_SWING if spec.timeframe == "1d" else KIND_INTRA
    return KIND_INFO


def target_of(spec: StrategySpec) -> str:
    """The trial target: `y_c2o_10` (daily per-stock and cross-sectional), `y_oc` (intraday), else `index`."""
    kind = eval_kind(spec)
    if kind in (KIND_SWING, KIND_XS):
        return "y_c2o_10"
    if kind in (KIND_INTRA, KIND_CAPITAL):
        return "y_oc"
    return "index"


def benchmark_of(spec: StrategySpec) -> str:
    """`ew500` (stock books), `nifty` (index timing) or `cash` (options, zero)."""
    if spec.family == "m-opt":
        return "cash"
    return "nifty" if spec.family == "m-index" else "ew500"


def trends_of(spec: StrategySpec) -> list[str]:
    """Trend filters that get a trial of their own (intraday per-stock strategies only)."""
    return list(TRENDS) if eval_kind(spec) == KIND_INTRA else []


def section_text(spec: StrategySpec) -> str:
    """The `[strategy.<key>]` section of one registered strategy."""
    q = json.dumps
    desc = spec.description.splitlines()[0] if spec.description else ""
    lines = [
        f"[strategy.{spec.key}]",
        f"name = {q(spec.name)}",
        f"source = {q(spec.source)}",
        f"tier = {q(spec.tier)}",
        f"family = {q(spec.family)}",
        f"timeframe = {q(spec.timeframe)}",
        f"kind = {q(spec.kind)}",
        f"direction = {q(spec.direction)}",
        f"exits = {q(list(spec.exits))}",
        f"default_exit = {q(spec.default_exit)}",
        "params = {}",
        f"strength = {q(spec.strength)}",
        f"status = {q(spec.status)}",
        f"eval = {q(eval_kind(spec))}",
        f"target = {q(target_of(spec))}",
        f"benchmark = {q(benchmark_of(spec))}",
    ]
    if trends_of(spec):
        lines.append(f"trends = {q(trends_of(spec))}")
    if spec.source == "k151":
        sec, eq = paper_ref(spec)
        lines += [f"paper_section = {q(sec)}", f"paper_eq = {q(eq)}"]
    lines += [f"hypothesis = {q(desc)}", f"reference = {q(spec.reference)}", ""]
    return "\n".join(lines)


def registry_toml_text() -> str:
    """The protocol header and one section per registered strategy (sorted by key)."""
    parts = [PROTOCOL]
    parts += [section_text(s) for _, s in sorted(load_library().items())]
    return "\n".join(parts)


@lru_cache(maxsize=4)
def load_toml(path: Path | None = None) -> dict[str, Any]:
    """Parse `config/strategy_library.toml` (or another pre-registered file)."""
    with (path or LIBRARY_PATH).open("rb") as f:
        return tomllib.load(f)


def library_section(key: str, path: Path | None = None) -> dict[str, Any]:
    """The pre-registered section of one strategy; KeyError when the file does not list it."""
    return dict(load_toml(path)["strategy"][key])


def protocol(path: Path | None = None) -> dict[str, Any]:
    """The `[protocol]` table."""
    return dict(load_toml(path)["protocol"])


def research_end(path: Path | None = None) -> date:
    """`protocol.research_end` as a date."""
    v = protocol(path)["research_end"]
    return v if isinstance(v, date) else date.fromisoformat(str(v))
